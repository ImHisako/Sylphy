#![cfg(feature = "signal-ratchet")]

use libsignal_protocol::{
    CiphertextMessage, DeviceId, GenericSignedPreKey, IdentityKeyPair, IdentityKeyStore,
    InMemSignalProtocolStore, KeyPair, KyberPreKeyRecord, KyberPreKeyStore, PreKeyBundle,
    PreKeyRecord, PreKeySignalMessage, PreKeyStore, ProtocolAddress, SessionRecord, SessionStore,
    SessionUsabilityRequirements, SignalMessage, SignedPreKeyRecord, SignedPreKeyStore, Timestamp,
    kem, message_decrypt, message_encrypt, process_prekey_bundle,
};
use rand::{TryRngCore as _, rngs::OsRng};
use serde::{Deserialize, Serialize};
use std::time::SystemTime;

// All keys in this fixture are disposable, public test material generated by
// older releases. Keeping the original bytes detects storage/wire regressions.
#[derive(Deserialize, Serialize)]
struct Fixture {
    provider: String,
    alice_identity: Vec<u8>,
    bob_identity: Vec<u8>,
    pre_key: Vec<u8>,
    signed_pre_key: Vec<u8>,
    kyber_pre_key: Vec<u8>,
    bootstrap_message: Vec<u8>,
    alice_session: Vec<u8>,
    bob_session: Vec<u8>,
    delayed_message: Vec<u8>,
    next_message: Vec<u8>,
}

fn previous_fixtures() -> [Fixture; 3] {
    [
        ("v0.102.1", include_str!("fixtures/libsignal-v0.102.1.json")),
        ("v0.105.0", include_str!("fixtures/libsignal-v0.105.0.json")),
        ("v0.105.1", include_str!("fixtures/libsignal-v0.105.1.json")),
    ]
    .map(|(version, document)| {
        let fixture: Fixture = serde_json::from_str(document).unwrap();
        assert_eq!(fixture.provider, format!("signalapp/libsignal@{version}"));
        fixture
    })
}

fn address(name: &str) -> ProtocolAddress {
    ProtocolAddress::new(name.to_owned(), DeviceId::new(1).unwrap())
}

fn store(identity: &[u8], registration: u32) -> InMemSignalProtocolStore {
    InMemSignalProtocolStore::new(IdentityKeyPair::try_from(identity).unwrap(), registration)
        .unwrap()
}

async fn encrypt(
    store: &mut InMemSignalProtocolStore,
    from: &ProtocolAddress,
    to: &ProtocolAddress,
    body: &[u8],
) -> CiphertextMessage {
    message_encrypt(
        body,
        to,
        from,
        &mut store.session_store,
        &mut store.identity_store,
        SystemTime::now(),
        &mut OsRng.unwrap_err(),
    )
    .await
    .unwrap()
}

async fn decrypt(
    store: &mut InMemSignalProtocolStore,
    from: &ProtocolAddress,
    to: &ProtocolAddress,
    message: &CiphertextMessage,
) -> Result<Vec<u8>, libsignal_protocol::SignalProtocolError> {
    message_decrypt(
        message,
        from,
        to,
        &mut store.session_store,
        &mut store.identity_store,
        &mut store.pre_key_store,
        &store.signed_pre_key_store,
        &mut store.kyber_pre_key_store,
        &mut OsRng.unwrap_err(),
    )
    .await
}

async fn restore_sessions(
    fixture: &Fixture,
) -> (InMemSignalProtocolStore, InMemSignalProtocolStore) {
    let mut alice = store(&fixture.alice_identity, 1);
    let mut bob = store(&fixture.bob_identity, 2);
    alice
        .identity_store
        .save_identity(
            &address("bob"),
            IdentityKeyPair::try_from(fixture.bob_identity.as_slice())
                .unwrap()
                .identity_key(),
        )
        .await
        .unwrap();
    bob.identity_store
        .save_identity(
            &address("alice"),
            IdentityKeyPair::try_from(fixture.alice_identity.as_slice())
                .unwrap()
                .identity_key(),
        )
        .await
        .unwrap();
    alice
        .session_store
        .store_session(
            &address("bob"),
            &SessionRecord::deserialize(&fixture.alice_session).unwrap(),
        )
        .await
        .unwrap();
    bob.session_store
        .store_session(
            &address("alice"),
            &SessionRecord::deserialize(&fixture.bob_session).unwrap(),
        )
        .await
        .unwrap();
    (alice, bob)
}

#[test]
fn previous_version_prekeys_and_pending_bootstrap_remain_readable() {
    futures_executor::block_on(async {
        for fixture in previous_fixtures() {
            let mut bob = store(&fixture.bob_identity, 2);
            bob.pre_key_store
                .save_pre_key(
                    1.into(),
                    &PreKeyRecord::deserialize(&fixture.pre_key).unwrap(),
                )
                .await
                .unwrap();
            bob.signed_pre_key_store
                .save_signed_pre_key(
                    1.into(),
                    &SignedPreKeyRecord::deserialize(&fixture.signed_pre_key).unwrap(),
                )
                .await
                .unwrap();
            bob.kyber_pre_key_store
                .save_kyber_pre_key(
                    1.into(),
                    &KyberPreKeyRecord::deserialize(&fixture.kyber_pre_key).unwrap(),
                )
                .await
                .unwrap();
            let message = CiphertextMessage::PreKeySignalMessage(
                PreKeySignalMessage::try_from(fixture.bootstrap_message.as_slice()).unwrap(),
            );
            assert_eq!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &message)
                    .await
                    .unwrap(),
                b"before-upgrade-bootstrap"
            );
        }
    });
}

#[test]
fn previous_version_sessions_keep_skipped_keys_and_bidirectional_messages() {
    futures_executor::block_on(async {
        for fixture in previous_fixtures() {
            let (mut alice, mut bob) = restore_sessions(&fixture).await;
            // Bob already received a later message with the old library, so this
            // requires restoring a skipped message key, not just an active chain.
            let delayed = CiphertextMessage::SignalMessage(
                SignalMessage::try_from(fixture.delayed_message.as_slice()).unwrap(),
            );
            assert_eq!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &delayed)
                    .await
                    .unwrap(),
                b"before-upgrade-delayed"
            );
            assert!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &delayed)
                    .await
                    .is_err()
            );
            let next = CiphertextMessage::SignalMessage(
                SignalMessage::try_from(fixture.next_message.as_slice()).unwrap(),
            );
            assert_eq!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &next)
                    .await
                    .unwrap(),
                b"before-upgrade-next"
            );
            let reply = encrypt(
                &mut bob,
                &address("bob"),
                &address("alice"),
                b"after-upgrade",
            )
            .await;
            assert_eq!(
                decrypt(&mut alice, &address("bob"), &address("alice"), &reply)
                    .await
                    .unwrap(),
                b"after-upgrade"
            );
            let outgoing = encrypt(
                &mut alice,
                &address("alice"),
                &address("bob"),
                b"after-upgrade-return",
            )
            .await;
            assert_eq!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &outgoing)
                    .await
                    .unwrap(),
                b"after-upgrade-return"
            );
        }
    });
}

#[test]
fn archived_legacy_sessions_decrypt_without_becoming_active_again() {
    futures_executor::block_on(async {
        for fixture in previous_fixtures() {
            let (_, mut bob) = restore_sessions(&fixture).await;
            let mut record = bob
                .session_store
                .load_session(&address("alice"))
                .await
                .unwrap()
                .unwrap();
            record.archive_current_state().unwrap();
            bob.session_store
                .store_session(&address("alice"), &record)
                .await
                .unwrap();
            let delayed = CiphertextMessage::SignalMessage(
                SignalMessage::try_from(fixture.delayed_message.as_slice()).unwrap(),
            );
            assert_eq!(
                decrypt(&mut bob, &address("alice"), &address("bob"), &delayed)
                    .await
                    .unwrap(),
                b"before-upgrade-delayed"
            );
            let record = bob
                .session_store
                .load_session(&address("alice"))
                .await
                .unwrap()
                .unwrap();
            assert!(
                !record
                    .has_usable_sender_chain(
                        SystemTime::now(),
                        SessionUsabilityRequirements::NotStale
                    )
                    .unwrap()
            );
        }
    });
}

// Run only with Cargo.toml and Cargo.lock pinned to the requested old version.
// Never regenerate an older-version fixture using the version under test.
#[test]
#[ignore = "fixture generator requires the corresponding old libsignal version"]
fn generate_previous_version_fixture() {
    let version =
        std::env::var("SYLPHY_GENERATE_FIXTURE_VERSION").unwrap_or_else(|_| "v0.102.1".to_owned());
    assert!(matches!(
        version.as_str(),
        "v0.102.1" | "v0.105.0" | "v0.105.1"
    ));
    let provider = format!("signalapp/libsignal@{version}");
    assert_eq!(
        sylphy_core::ratchet_adapter::capability_status().provider,
        provider
    );
    futures_executor::block_on(async {
        let mut rng = OsRng.unwrap_err();
        let alice_identity = IdentityKeyPair::generate(&mut rng);
        let bob_identity = IdentityKeyPair::generate(&mut rng);
        let mut alice = InMemSignalProtocolStore::new(alice_identity, 1).unwrap();
        let mut bob = InMemSignalProtocolStore::new(bob_identity, 2).unwrap();
        let pre_key = PreKeyRecord::new(1.into(), &KeyPair::generate(&mut rng));
        let signed_pair = KeyPair::generate(&mut rng);
        let signed_signature = bob_identity
            .private_key()
            .calculate_signature(&signed_pair.public_key.serialize(), &mut rng)
            .unwrap();
        let signed_pre_key = SignedPreKeyRecord::new(
            1.into(),
            Timestamp::from_epoch_millis(1_792_022_400_000),
            &signed_pair,
            &signed_signature,
        );
        let kyber_pair = kem::KeyPair::generate(kem::KeyType::Kyber1024, &mut rng);
        let kyber_signature = bob_identity
            .private_key()
            .calculate_signature(&kyber_pair.public_key.serialize(), &mut rng)
            .unwrap();
        let kyber_pre_key = KyberPreKeyRecord::new(
            1.into(),
            Timestamp::from_epoch_millis(1_792_022_400_000),
            &kyber_pair,
            &kyber_signature,
        );
        bob.pre_key_store
            .save_pre_key(1.into(), &pre_key)
            .await
            .unwrap();
        bob.signed_pre_key_store
            .save_signed_pre_key(1.into(), &signed_pre_key)
            .await
            .unwrap();
        bob.kyber_pre_key_store
            .save_kyber_pre_key(1.into(), &kyber_pre_key)
            .await
            .unwrap();
        let bundle = PreKeyBundle::new(
            2,
            DeviceId::new(1).unwrap(),
            Some((1.into(), pre_key.public_key().unwrap())),
            1.into(),
            signed_pair.public_key,
            signed_signature.to_vec(),
            1.into(),
            kyber_pair.public_key,
            kyber_signature.to_vec(),
            *bob_identity.identity_key(),
        )
        .unwrap();
        process_prekey_bundle(
            &address("bob"),
            &address("alice"),
            &mut alice.session_store,
            &mut alice.identity_store,
            &bundle,
            SystemTime::now(),
            &mut rng,
        )
        .await
        .unwrap();
        let bootstrap = encrypt(
            &mut alice,
            &address("alice"),
            &address("bob"),
            b"before-upgrade-bootstrap",
        )
        .await;
        decrypt(&mut bob, &address("alice"), &address("bob"), &bootstrap)
            .await
            .unwrap();
        let ack = encrypt(&mut bob, &address("bob"), &address("alice"), b"ack").await;
        decrypt(&mut alice, &address("bob"), &address("alice"), &ack)
            .await
            .unwrap();
        let delayed = encrypt(
            &mut alice,
            &address("alice"),
            &address("bob"),
            b"before-upgrade-delayed",
        )
        .await;
        let later = encrypt(&mut alice, &address("alice"), &address("bob"), b"later").await;
        decrypt(&mut bob, &address("alice"), &address("bob"), &later)
            .await
            .unwrap();
        let next = encrypt(
            &mut alice,
            &address("alice"),
            &address("bob"),
            b"before-upgrade-next",
        )
        .await;
        let fixture = Fixture {
            provider,
            alice_identity: alice_identity.serialize().to_vec(),
            bob_identity: bob_identity.serialize().to_vec(),
            pre_key: pre_key.serialize().unwrap(),
            signed_pre_key: signed_pre_key.serialize().unwrap(),
            kyber_pre_key: kyber_pre_key.serialize().unwrap(),
            bootstrap_message: bootstrap.serialize().to_vec(),
            alice_session: alice
                .session_store
                .load_session(&address("bob"))
                .await
                .unwrap()
                .unwrap()
                .serialize()
                .unwrap(),
            bob_session: bob
                .session_store
                .load_session(&address("alice"))
                .await
                .unwrap()
                .unwrap()
                .serialize()
                .unwrap(),
            delayed_message: delayed.serialize().to_vec(),
            next_message: next.serialize().to_vec(),
        };
        std::fs::write(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/fixtures")
                .join(format!("libsignal-{version}.json")),
            serde_json::to_vec(&fixture).unwrap(),
        )
        .unwrap();
    });
}
